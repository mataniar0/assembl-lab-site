import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const utf=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const binary=path=>readFileSync(new URL(path,import.meta.url));
const sha=x=>createHash('sha256').update(x).digest('hex');
const model='./assets/personal-coffee-showroom-v2.glb';
const poster='./assets/personal-coffee-showroom-v2.webp';
const metadata='./assets/personal-coffee-showroom-v2.json';

test('model and photostyled hero are tied to the EXACT same GLB bytes and real source prototype',()=>{
  const info=JSON.parse(utf(metadata));
  const glb=binary(model),webp=binary(poster);
  const source=binary('../table/personal/media/personal-design-preview.glb');
  assert.equal(info.kind,'SHOWROOM_VISUAL_ONLY');
  assert.equal(info.product,'personal-coffee-table');
  assert.equal(info.source_model_sha256,sha(source));
  assert.equal(info.showroom_model_sha256,sha(glb));
  assert.equal(info.poster_rendered_from_model_sha256,sha(glb));
  assert.equal(info.poster_webp_sha256,sha(webp));
  assert.deepEqual(info.poster_pixels,[960,820]);
  assert.match(info.render_pipeline,/model-viewer 4\.1\.0/);
  assert.equal(glb.toString('ascii',0,4),'glTF');
  assert.equal(glb.readUInt32LE(4),2);
  assert.equal(glb.readUInt32LE(8),glb.byteLength);
  assert.equal(webp.toString('ascii',0,4),'RIFF');
  assert.equal(webp.toString('ascii',8,12),'WEBP');
  assert.ok(glb.length>100_000);
  assert.ok(webp.length>8_000);
  assert.equal(info.engineering_approval,false);
  assert.equal(info.manufacturing_approval,false);
});
test('visual redesign has photo-informed proportions, curved three-leg silhouette and actual ring geometry',()=>{
  const info=JSON.parse(utf(metadata));
  assert.equal(info.source_model_geometry_count,32);
  assert.ok(info.showroom_geometry_count>=10);
  assert.ok(info.visual_dimensions_estimate_m.top_diameter>=.55);
  assert.ok(info.visual_dimensions_estimate_m.top_edge_thickness>=.04);
  const [mins,maxs]=info.showroom_bounds_m;
  // glTF Y-up after conversion from the original project's Z-up geometry:
  assert.ok(maxs[1]-mins[1]>.47,'table is upright, not lying on its side');
  assert.ok(maxs[0]-mins[0]>.55,'round top has corrected proportional span');
  assert.ok(maxs[2]-mins[2]>.55,'round top has corrected front-to-back span');
  assert.ok(info.features.some(v=>/ring brace/i.test(v)));
  assert.ok(info.features.some(v=>/curved black/i.test(v)));
});
