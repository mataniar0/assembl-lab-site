import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const binary=path=>readFileSync(new URL(path,import.meta.url));
const checksum=bytes=>createHash('sha256').update(bytes).digest('hex');

test('showcase hero is authentic finished product photograph, not cartoon or synthetic 3D screenshot',()=>{
  const html=read('./index.html'),hero=read('./personal-coffee-hero.mjs');
  const image=binary('../table/personal/media/01-hero-finished-angled-960.webp');
  assert.equal(image.toString('ascii',0,4),'RIFF');
  assert.equal(image.toString('ascii',8,12),'WEBP');
  assert.equal(image.length,122958);
  assert.match(html,/01-hero-finished-angled-480\.webp/);
  assert.match(html,/01-hero-finished-angled-960\.webp/);
  assert.match(html,/data-he="צילום המוצר"/);
  assert.match(html,/התמונה היא צילום השולחן שנבנה בפועל/);
  assert.match(html,/בעל 32 חלקים/);
  assert.match(html,/href="\.\.\/table\/personal\/"/);
  assert.match(hero,/photo-grounded-coffee-glb\.mjs/);
  assert.match(hero,/verifyPersonalSource\(original\)/);
  assert.match(hero,/finishPersonalDesign\(original\)/);
  assert.doesNotMatch(hero,/toDataURL|snapshotFromLoadedModel|matchingCoffeeTableGlb/);
  assert.doesNotMatch(html,/תמונת הראווה נוצרת מתוך אותו GLB/);
});
test('the exact frozen original 3D and site source photos remain unchanged',()=>{
  const source=binary('../table/personal/media/personal-design-preview.glb');
  const product=read('../table/personal/index.html');
  assert.equal(source.byteLength,1700936);
  assert.equal(checksum(source),'17da2aafb7f17182b940804c22cb2be8dc0430cad26f20c76ca78e08ae9b8841');
  assert.match(product,/המבנה והגימור אינם העתק מאומת/);
  assert.match(product,/01-hero-finished-angled-960\.webp/);
});
test('only same-origin local library and original GLB source, no cloud/AI or PWA privacy regression',()=>{
  const html=read('./index.html'),source=read('./personal-coffee-hero.mjs');
  const sw=read('./sw.js'),css=read('./personal-coffee-hero.css');
  assert.match(html,/id="personal-coffee-photo"/);
  assert.match(html,/id="personal-coffee-model"/);
  assert.match(html,/data-model-src="\.\.\/table\/personal\/media\/personal-design-preview\.glb"/);
  assert.match(source,/vendor\/model-viewer-4\.1\.0\/model-viewer\.min\.js/);
  assert.match(source,/personal-design-preview\.glb/);
  assert.match(source,/new Blob\(\[output\],\{type:'model\/gltf-binary'\}\)/);
  assert.match(source,/URL\.revokeObjectURL/);
  assert.match(source,/webGLAvailable/);
  assert.match(source,/fetch\(source3d\)/);
  assert.match(css,/\.personal-coffee-card/);
  assert.match(sw,/'\.\/photo-grounded-coffee-glb\.mjs'/);
  assert.match(sw,/'\.\.\/table\/personal\/media\/personal-design-preview\.glb'/);
  assert.match(sw,/'\.\.\/table\/personal\/media\/01-hero-finished-angled-960\.webp'/);
  assert.match(html,/script-src 'self' 'sha256-GBnlKux09VbgrayAnLRJMrWvjFuJ9hF2QuT9vewZR6U=' 'wasm-unsafe-eval'/);
  assert.doesNotMatch(source,/XMLHttpRequest|localStorage|sessionStorage|indexedDB|supabase|openai|cdn\./i);
});
